export function createMothxLogo(): HTMLImageElement {
  const image = document.createElement('img');
  image.src = 'mothx.png';
  image.alt = '';
  image.setAttribute('aria-hidden', 'true');
  return image;
}

// hydrateIcons 替换所有 <span class="wi" data-icon="name"> 为内联 SVG。
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('.wi[data-icon]').forEach((el) => {
    if (el.dataset.hydrated === '1') return;
    el.dataset.hydrated = '1';
    el.innerHTML = iconSVG(el.dataset.icon || 'doc');
  });
}
